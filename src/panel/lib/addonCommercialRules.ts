const normalize = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
export function officialAddon(addon: { code: string; name: string }) {
  return OFFICIAL_19_ADDONS.find(
    (item) =>
      normalize(item.internalCode) === normalize(addon.code) ||
      normalize(item.name) === normalize(addon.name),
  );
}
export function addonCommercialPending(addon: { code: string; name: string } | null) {
  return !addon || officialAddon(addon)?.code === "ADD-18";
}
export function validateAddonCommercial(
  addon: { code: string; name: string },
  price: number | null,
  setup: number,
  billing: string,
): string | null {
  if (addonCommercialPending(addon))
    return "Preço e escopo pendentes de aprovação; contratação indisponível.";
  const approved = officialAddon(addon);
  if (!approved)
    return "Adicional sem condições comerciais identificadas. Conferir aprovação antes de contratar.";
  if (price !== approved.price || billing !== approved.billing)
    return "Use o preço e a periodicidade comercial aprovados.";
  if (setup !== 0) return "Não há taxa de implantação aprovada para esta nova contratação.";
  return null;
}
